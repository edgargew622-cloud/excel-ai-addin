"""Книга для проверок оформления: format-smoke.xlsx.

Лист «Сотрудники» намеренно голый: ни шрифтов, ни границ, ни ширины. Каждое
изменение оформления здесь видно глазом, и его легко сверить по файлу.
Длинные должности и комментарии подобраны так, чтобы автоподбор ширины
и перенос по словам заметно меняли вид.

Лист «Смешанное» готовит два особых случая:

    A1:C4  внутри уже есть тонкие серые линии — рамка «outline» не должна
           их тронуть, а проверка не должна считать их расхождением;
    E1:E4  в двух ячейках курсив, в двух нет — предпросмотр обязан сказать
           «разное в области», а не «нет».
"""
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Border, Font, Side

root = Path(__file__).resolve().parent.parent
target = root / "format-smoke.xlsx"

wb = Workbook()
staff = wb.active
staff.title = "Сотрудники"
staff.append(["ФИО", "Должность", "Отдел", "Оклад", "Комментарий"])
rows = [
    ("Иванов Иван", "Ведущий специалист по работе с ключевыми клиентами", "Продажи", 185000, "Перевод в новый отдел с октября"),
    ("Петрова Анна", "Бухгалтер", "Финансы", 95000, "—"),
    ("Сидоров Пётр", "Руководитель направления развития партнёрской сети", "Развитие", 240000, "Испытательный срок до конца года, затем пересмотр оклада"),
    ("Кузнецова Мария", "Аналитик", "Финансы", 120000, "—"),
    ("Смирнов Олег", "Инженер", "Производство", 110000, "Отпуск в ноябре"),
    ("Попова Елена", "Юрист", "Правовой", 150000, "—"),
]
for row in rows:
    staff.append(row)

mixed = wb.create_sheet("Смешанное")
thin_grey = Side(style="thin", color="C0C0C0")
for r in range(1, 5):
    for c in range(1, 4):
        cell = mixed.cell(r, c, value=f"{r}.{c}")
        cell.border = Border(left=thin_grey, right=thin_grey, top=thin_grey, bottom=thin_grey)
for r in range(1, 5):
    cell = mixed.cell(r, 5, value=f"текст {r}")
    if r <= 2:
        cell.font = Font(italic=True)

wb.save(target)
print(f"Книга сохранена: {target}")
