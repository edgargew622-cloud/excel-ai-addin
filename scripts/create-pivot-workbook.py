"""Книга для проверок сводной таблицы: pivot-smoke.xlsx.

«Заказы» — двенадцать заказов по трём городам. Итоги известны заранее,
и по ним видно, свела ли Excel то, что посчитала панель:

    Москва  4 заказа, сумма 3 950
    Казань  4 заказа, сумма 2 150
    Омск    4 заказа, сумма 4 900
    Всего  12 заказов, сумма 11 000

Столбец «Менеджер» — текст: сумма по нему должна вызвать предупреждение,
а количество — нет.

«Занято» — те же заказы, но в H3 стоит заметка. Сводная правее данных
заденет её, и операция обязана отказать, а не затереть.

«Связанные» — заказы, у которых сумма считается формулой через курс
с листа «Курс» (сейчас 1, итог 11 000). Если после предпросмотра сменить
курс, текст формул не изменится, а суммы — да: расчёт панели устареет,
и сводная обязана остановиться (план стабилизации, S2).
"""
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font

root = Path(__file__).resolve().parent.parent
target = root / "pivot-smoke.xlsx"

orders = [
    ("Москва", "Новая", 900, "Иванов"),
    ("Москва", "В работе", 1200, "Иванов"),
    ("Москва", "Закрыта", 450, "Сидоров"),
    ("Москва", "Закрыта", 1400, "Петрова"),
    ("Казань", "Новая", 700, "Петрова"),
    ("Казань", "В работе", 250, "Иванов"),
    ("Казань", "Закрыта", 800, "Сидоров"),
    ("Казань", "Новая", 400, "Петрова"),
    ("Омск", "Новая", 1500, "Сидоров"),
    ("Омск", "В работе", 1100, "Иванов"),
    ("Омск", "Закрыта", 1300, "Петрова"),
    ("Омск", "Новая", 1000, "Сидоров"),
]

wb = Workbook()
for title in ("Заказы", "Занято"):
    ws = wb.active if title == "Заказы" else wb.create_sheet(title)
    ws.title = title
    ws.append(["Город", "Статус", "Сумма", "Менеджер"])
    for row in orders:
        ws.append(row)
    for cell in ws[1]:
        cell.font = Font(bold=True)
    ws.column_dimensions["B"].width = 12
wb["Занято"]["H3"] = "заметка — не затирать"

rate = wb.create_sheet("Курс")
rate["A1"] = "Курс"
rate["B1"] = 1

linked = wb.create_sheet("Связанные")
linked.append(["Город", "Статус", "Сумма", "Менеджер"])
for index, (city, status, amount, manager) in enumerate(orders, start=2):
    linked.append([city, status, f"={amount}*Курс!$B$1", manager])
for cell in linked[1]:
    cell.font = Font(bold=True)

wb.save(target)
print(f"Книга сохранена: {target}")
