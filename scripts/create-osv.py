"""Синтетическая оборотно-сальдовая ведомость в виде отчёта 1С (24.10.2026).

Проводки двойной записью → остатки и обороты по субсчетам → ОСВ с синтетическими
строками и субсчетами, как её сохраняет 1С в Excel. Все организации и числа
вымышленные. Ожидаемые строки форм 1 и 2 печатаются для проверки.

    python scripts/create-osv.py <out.xlsx> [<out.json>]
"""
import json, sys
from collections import defaultdict

NAMES = {
    "01": "Основные средства", "02": "Амортизация основных средств", "08": "Вложения во внеоборотные активы", "10": "Материалы",
    "19": "НДС по приобретенным ценностям", "20": "Основное производство", "26": "Общехозяйственные расходы", "41": "Товары",
    "44": "Расходы на продажу", "50": "Касса", "51": "Расчетные счета", "60": "Расчеты с поставщиками и подрядчиками",
    "60.01": "Расчеты с поставщиками и подрядчиками", "60.02": "Расчеты по авансам выданным", "62": "Расчеты с покупателями и заказчиками",
    "62.01": "Расчеты с покупателями и заказчиками", "62.02": "Расчеты по авансам полученным", "66": "Расчеты по краткосрочным кредитам и займам",
    "67": "Расчеты по долгосрочным кредитам и займам", "68": "Расчеты по налогам и сборам", "68.01": "НДФЛ при исполнении обязанностей налогового агента",
    "68.02": "Налог на добавленную стоимость", "68.04": "Налог на прибыль", "69": "Расчеты по социальному страхованию", "70": "Расчеты с персоналом по оплате труда",
    "71": "Расчеты с подотчетными лицами", "76": "Расчеты с разными дебиторами и кредиторами", "80": "Уставный капитал", "84": "Нераспределенная прибыль (непокрытый убыток)",
    "90": "Продажи", "90.01": "Выручка", "90.02": "Себестоимость продаж", "90.03": "Налог на добавленную стоимость", "90.07": "Расходы на продажу",
    "90.08": "Управленческие расходы", "90.09": "Прибыль / убыток от продаж", "91": "Прочие доходы и расходы", "91.01": "Прочие доходы", "91.02": "Прочие расходы",
    "91.09": "Сальдо прочих доходов и расходов", "99": "Прибыли и убытки", "99.01": "Прибыли и убытки (кроме налога на прибыль)", "99.02": "Налог на прибыль"
}

opening = {  # счёт: (Дт, Кт) на начало периода
    "01": (4_800_000, 0), "02": (0, 1_350_000), "10": (420_000, 0), "41": (1_960_000, 0), "50": (18_000, 0), "51": (2_240_000, 0),
    "60.01": (0, 780_000), "60.02": (150_000, 0), "62.01": (1_310_000, 0), "62.02": (0, 240_000), "66": (0, 600_000), "67": (0, 1_500_000),
    "68.01": (0, 64_000), "68.02": (0, 210_000), "68.04": (0, 95_000), "69": (0, 120_000), "70": (0, 380_000), "71": (6_500, 0), "76": (85_000, 40_000),
    "80": (0, 100_000), "84": (0, 5_711_500), "19": (95_000, 0)
}
po = [  # Дт, Кт, сумма
    ("41", "60.01", 3_200_000), ("19", "60.01", 640_000), ("60.01", "51", 3_500_000), ("60.02", "51", 300_000), ("60.01", "60.02", 250_000),
    ("10", "60.01", 380_000), ("19", "60.01", 76_000), ("20", "10", 510_000), ("26", "70", 920_000), ("26", "69", 276_000), ("44", "70", 640_000), ("44", "69", 192_000),
    ("70", "68.01", 202_000), ("70", "51", 1_390_000), ("69", "51", 430_000), ("68.01", "51", 230_000), ("08", "60.01", 450_000), ("19", "60.01", 90_000),
    ("01", "08", 450_000), ("26", "02", 185_000), ("44", "02", 40_000), ("62.01", "90.01", 9_600_000), ("90.03", "68.02", 1_600_000),
    ("90.02", "41", 4_150_000), ("90.02", "20", 510_000), ("90.07", "44", 872_000), ("90.08", "26", 1_395_200), ("51", "62.01", 8_900_000),
    ("51", "62.02", 480_000), ("62.02", "62.01", 360_000), ("68.02", "19", 806_000), ("68.02", "51", 520_000), ("51", "66", 400_000), ("66", "51", 600_000),
    ("91.02", "66", 54_000), ("91.02", "67", 165_000), ("66", "51", 54_000), ("51", "91.01", 38_000), ("91.02", "51", 24_000), ("71", "50", 15_000),
    ("26", "71", 14_200), ("50", "51", 20_000), ("76", "91.01", 12_000), ("91.02", "76", 9_500), ("50", "62.01", 4_000)
]
# Нераспределённая прибыль на начало — балансирующая: Дт = Кт.
opening["84"] = (0, opening["84"][1] + sum(d - k for d, k in opening.values()))
balance = defaultdict(int)
for acc, (d, k) in opening.items(): balance[acc] += d - k
start = dict(balance)
td = defaultdict(int); tc = defaultdict(int)
def post(d, k, s):
    balance[d] += s; balance[k] -= s; td[d] += s; tc[k] += s
for d, k, s in po: post(d, k, s)
# Закрытие 90 и 91 на 99, налог на прибыль 20 % от прибыли до налога.
p90 = -(balance["90.01"] + balance["90.02"] + balance["90.03"] + balance["90.07"] + balance["90.08"])
post("90.09", "99.01", p90) if p90 >= 0 else post("99.01", "90.09", -p90)
p91 = -(balance["91.01"] + balance["91.02"])
post("91.09", "99.01", p91) if p91 >= 0 else post("99.01", "91.09", -p91)
tax = round((p90 + p91) * 0.2)
post("99.02", "68.04", tax)

accounts = sorted(set(list(opening) + [a for p in po for a in p[:2]] + ["90.09", "91.09", "99.01", "99.02", "68.04"]))
subs = defaultdict(list)
for a in accounts:
    top = a.split(".")[0]
    if "." in a: subs[top].append(a)
tops = sorted(set(a.split(".")[0] for a in accounts))
def side(v): return (v, 0) if v > 0 else (0, -v)
rows = []
for top in tops:
    children = subs.get(top, [])
    if children:
        sd = sum(side(start.get(c, 0))[0] for c in children); sc = sum(side(start.get(c, 0))[1] for c in children)
        ed = sum(side(balance[c])[0] for c in children); ec = sum(side(balance[c])[1] for c in children)
        rows.append([top, NAMES.get(top, ""), sd, sc, sum(td[c] for c in children), sum(tc[c] for c in children), ed, ec])
        for c in children:
            s0 = side(start.get(c, 0)); s1 = side(balance[c])
            rows.append([c, NAMES.get(c, ""), s0[0], s0[1], td[c], tc[c], s1[0], s1[1]])
    else:
        s0 = side(start.get(top, 0)); s1 = side(balance[top])
        rows.append([top, NAMES.get(top, ""), s0[0], s0[1], td[top], tc[top], s1[0], s1[1]])
synth = [r for r in rows if "." not in r[0]]
total = ["Итого", "", *[sum(r[i] for r in synth) for i in range(2, 8)]]
grid = [["ООО «Пример Торг»", "", "", "", "", "", "", ""], ["Оборотно-сальдовая ведомость за 9 месяцев 2026 г.", "", "", "", "", "", "", ""], [""] * 8,
        ["Счет", "Наименование счета", "Сальдо на начало периода", "", "Обороты за период", "", "Сальдо на конец периода", ""],
        ["", "", "Дебет", "Кредит", "Дебет", "Кредит", "Дебет", "Кредит"]] + rows + [total]

def b(a, which):
    v = balance.get(a, 0) if which == "end" else start.get(a, 0)
    return v
def debit_parts(top, which):
    children = subs.get(top) or [top]
    return sum(max(b(c, which), 0) for c in children)
def credit_parts(top, which):
    children = subs.get(top) or [top]
    return sum(max(-b(c, which), 0) for c in children)
def expected(which):
    e = {}
    e["1150"] = debit_parts("01", which) - credit_parts("02", which)
    e["1190"] = debit_parts("08", which)
    e["1210"] = sum(debit_parts(a, which) for a in ["10", "20", "41", "44"])
    e["1220"] = debit_parts("19", which)
    e["1230"] = sum(debit_parts(a, which) for a in ["60", "62", "68", "69", "70", "71", "76"])
    e["1250"] = debit_parts("50", which) + debit_parts("51", which)
    e["1600"] = sum(e.values())
    e["1310"] = credit_parts("80", which)
    e["1370"] = credit_parts("84", which) - debit_parts("84", which) + credit_parts("99", which) - debit_parts("99", which)
    e["1410"] = credit_parts("67", which); e["1510"] = credit_parts("66", which)
    e["1520"] = sum(credit_parts(a, which) for a in ["60", "62", "68", "69", "70", "71", "76"])
    e["1700"] = e["1310"] + e["1370"] + e["1410"] + e["1510"] + e["1520"]
    return e
results = {"2110": tc["90.01"] - td["90.03"], "2120": td["90.02"], "2210": td["90.07"], "2220": td["90.08"], "2340": tc["91.01"], "2350": td["91.02"], "2410": td["99.02"]}
results["2400"] = results["2110"] - results["2120"] - results["2210"] - results["2220"] + results["2340"] - results["2350"] - results["2410"]
exp = {"end": expected("end"), "start": expected("start"), "results": results}

if len(sys.argv) > 1:
    import openpyxl
    from openpyxl.styles import Font
    wb = openpyxl.Workbook(); ws = wb.active; ws.title = "ОСВ"
    for r in grid: ws.append(r)
    ws.merge_cells("C4:D4"); ws.merge_cells("E4:F4"); ws.merge_cells("G4:H4")
    for row in ws.iter_rows(min_row=6, min_col=3, max_col=8):
        for c in row: c.number_format = "#,##0.00"
    for row in ws.iter_rows(min_row=4, max_row=5):
        for c in row: c.font = Font(bold=True)
    # Ширины как в выгрузке 1С: суммы видны целиком, без «####».
    ws.column_dimensions["A"].width = 8
    ws.column_dimensions["B"].width = 52
    for col in "CDEFGH": ws.column_dimensions[col].width = 16
    wb.save(sys.argv[1])
if len(sys.argv) > 2:
    json.dump({"grid": grid, "expected": exp}, open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False)
print(json.dumps(exp, ensure_ascii=False))
